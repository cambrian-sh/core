const setupBunBaseURL = "https://github.com/oven-sh/bun/releases/latest/download/"

// bunAsset maps GOOS/GOARCH to the official bun release asset name.
func bunAsset(goos, goarch string) (string, bool) {
	arch := map[string]string{"amd64": "x64", "arm64": "aarch64"}[goarch]
	if arch == "" {
		return "", false
	}
	switch goos {
	case "linux", "darwin":
		return "bun-" + goos + "-" + arch + ".zip", true
	case "windows":
		if arch != "x64" {
			return "", false
		}
		return "bun-windows-x64.zip", true
	}
	return "", false
}

// ensureBun finds bun on PATH or in <prefix>/bin. Downloading it there happens
// only when `download` is true (i.e. JS agent units exist — a ~90MB fetch is
// not paid for a Python-only fleet). Returns "" when bun is unavailable.
func (s *setupState) ensureBun(ctx context.Context, download bool) string {
	if s.bunBin != "" {
		return s.bunBin
	}
	if p, err := exec.LookPath("bun"); err == nil {
		s.bunBin = p
		return p
	}
	local := filepath.Join(s.prefix, "bin", exeName("bun"))
	if fileExists(local) {
		s.bunBin = local
		return local
	}
	if !download {
		return ""
	}
	asset, ok := bunAsset(runtime.GOOS, runtime.GOARCH)
	if !ok {
		return ""
	}
	fmt.Print("  downloading bun (JS agent runtime)… ")
	tmp, err := downloadTemp(ctx, setupBunBaseURL+asset)
	if err != nil {
		fmt.Println(s.ui.yellow("failed"))
		s.ui.line("warn", "bun download failed", err.Error())
		return ""
	}
	defer os.Remove(tmp)
	if err := extractOneFromZip(tmp, "bun", local); err != nil {
		fmt.Println(s.ui.yellow("failed"))
		s.ui.line("warn", "bun extract failed", err.Error())
		return ""
	}
	_ = os.Chmod(local, 0o755)
	fmt.Println(s.ui.green("done"))
	s.bunBin = local
	return local
}

// hasJSAgents reports whether any JS agent unit lives under agentsDir: an
// *agent.ts / *agent.js entry file, or any package.json (node_modules skipped).
func hasJSAgents(agentsDir string) bool {
	found := false
	_ = filepath.WalkDir(agentsDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() {
			if d.Name() == "node_modules" {
				return fs.SkipDir
			}
			return nil
		}
		n := d.Name()
		if n == "package.json" || strings.HasSuffix(n, "agent.ts") || strings.HasSuffix(n, "agent.js") {
			found = true
			return fs.SkipAll
		}
		return nil
	})
	return found
}

// jsPackageDirs returns every dir under agentsDir carrying a package.json
// (node_modules skipped), agents root first — the union-workspace install
// order (ADR-0125 D6).
func jsPackageDirs(agentsDir string) []string {
	var dirs []string
	_ = filepath.WalkDir(agentsDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() && d.Name() == "node_modules" {
			return fs.SkipDir
		}
		if !d.IsDir() && d.Name() == "package.json" {
			dirs = append(dirs, filepath.Dir(p))
		}
		return nil
	})
	// WalkDir is lexical, which already visits the root before its subtrees;
	// the explicit sort keeps that contract obvious and deterministic.
	slices.Sort(dirs)
	return dirs
}

func downloadTemp(ctx context.Context, rawURL string) (string, error) {
	cctx, cancel := context.WithTimeout(ctx, 5*time.Minute)
	defer cancel()
	req, err := http.NewRequestWithContext(cctx, http.MethodGet, rawURL, nil)
	if err != nil {
		return "", err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("GET %s: %s", rawURL, resp.Status)
	}
	f, err := os.CreateTemp("", "cambrian-setup-*")
	if err != nil {
		return "", err
	}
	if _, err := io.Copy(f, resp.Body); err != nil {
		f.Close()
		os.Remove(f.Name())
		return "", err
	}
	if err := f.Close(); err != nil {
		os.Remove(f.Name())
		return "", err
	}
	return f.Name(), nil
}

// extractOneFromZip pulls the single file whose base name matches out of a zip
// archive into dest (0755). Dest is chosen by us, so no zip-slip surface.
func extractOneFromZip(archive, base, dest string) error {
	zr, err := zip.OpenReader(archive)
	if err != nil {
		return err
	}
	defer zr.Close()
	for _, f := range zr.File {
		n := path.Base(f.Name)
		if n != base && n != base+".exe" {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return err
		}
		defer rc.Close()
		return writeExecutable(dest, rc)
	}
	return fmt.Errorf("%s not found in archive", base)
}

func extractOneFromTarGz(archive, base, dest string) error {
	f, err := os.Open(archive)
	if err != nil {
		return err
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		return err
	}
	defer gz.Close()
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
		if hdr.Typeflag != tar.TypeReg {
			continue
		}
		n := path.Base(hdr.Name)
		if n == base || n == base+".exe" {
			return writeExecutable(dest, tr)
		}
	}
	return fmt.Errorf("%s not found in archive", base)
}

func writeExecutable(dest string, r io.Reader) error {
	out, err := os.OpenFile(dest, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0o755)
	if err != nil {
		return err
	}
	// 512MB cap: bounds decompression; the uv binary is ~40MB.
	if _, err := io.Copy(out, io.LimitReader(r, 512<<20)); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

// ---- embedded agents ---------------------------------------------------------------------

// unpackAgents materializes the embedded agent sources into dst, refreshing
// existing files and filtering build junk (__pycache__, *.pyc, node_modules,
// *.map — the JS dependency tree is provisioned by `bun install` at setup
// time, never shipped inside the binary; ADR-0125 D7). Returns the number of
// files written.
func unpackAgents(dst string) (int, error) {
	n := 0
	err := fs.WalkDir(core.AgentsFS, "agents", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == "__pycache__" || d.Name() == "node_modules" {
				return fs.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(p, ".pyc") || strings.HasSuffix(p, ".map") {
			return nil
		}
		rel := strings.TrimPrefix(p, "agents/")
		out := filepath.Join(dst, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
			return err
		}
		b, err := core.AgentsFS.ReadFile(p)
		if err != nil {
			return err
		}
		if err := os.WriteFile(out, b, 0o644); err != nil {
			return err
		}
		n++
		return nil
	})
	return n, err
}

type setupMissingDep struct{ agent, mods string }

func parseSelfCheck(out string) []setupMissingDep {
	var res []setupMissingDep
	for ln := range strings.SplitSeq(out, "\n") {
		if !strings.HasPrefix(ln, "MISSING\t") {
			continue
		}
		parts := strings.SplitN(strings.TrimSpace(ln), "\t", 3)
		if len(parts) == 3 {
			res = append(res, setupMissingDep{agent: parts[1], mods: parts[2]})
		}
	}
	return res
}

// ---- config bundle -----------------------------------------------------------------------

// writeConfigBundle materializes <prefix>/configs/{config.json,tuning.json}.
// An existing config.json is merged (only the fields setup owns are set), so
// re-running setup never clobbers hand-edits; a fresh install seeds from the
// embedded config.example.json. tuning.json doubles as the ResolveBaseDir
// sentinel, so it is always ensured. Also records the server port for the
// readiness poll.
func (s *setupState) writeConfigBundle() error {
	cfgDir := filepath.Join(s.prefix, "configs")
	if err := os.MkdirAll(cfgDir, 0o755); err != nil {
		return err
	}
	cfgPath := filepath.Join(cfgDir, "config.json")

	var cfg map[string]any
	if b, err := os.ReadFile(cfgPath); err == nil {
		// Windows editors routinely save a UTF-8 BOM; strip it before parsing.
		b = bytes.TrimPrefix(b, []byte{0xEF, 0xBB, 0xBF})
		if uerr := json.Unmarshal(b, &cfg); uerr != nil {
			// Never clobber a file the operator hand-edited: a merge that treats
			// "unparseable" as "absent" silently destroys their config.
			return fmt.Errorf("existing %s is not valid JSON (%v) — fix or remove it; refusing to overwrite", cfgPath, uerr)
		}
	}
	if cfg == nil {
		if b, err := core.ConfigTemplatesFS.ReadFile("configs/config.example.json"); err == nil {
			_ = json.Unmarshal(b, &cfg)
		}
	}
	if cfg == nil {
		cfg = map[string]any{}
	}
	delete(cfg, "_comment")

	cfg["database"] = map[string]any{
		"host": s.db.host, "port": s.db.port, "user": s.db.user,
		"password": s.db.password, "dbname": s.db.dbname,
	}

	dbName := "agents.db"
	if st, ok := cfg["storage"].(map[string]any); ok {
		if v, ok := st["db_name"].(string); ok && v != "" {
			dbName = v
		}
	}
	cfg["storage"] = map[string]any{"data_dir": filepath.Join(s.prefix, "data"), "db_name": dbName}

	met, _ := cfg["metabolism"].(map[string]any)
	if met == nil {
		met = map[string]any{}
	}
	if s.venvPy != "" {
		met["python_executable"] = s.venvPy
	} else if vp := venvPython(filepath.Join(s.prefix, "venv")); fileExists(vp) {
		met["python_executable"] = vp
	}
	// ADR-0125: record the JS runtimes when resolved; absent keys keep the
	// kernel's $PATH fallback.
	if s.bunBin != "" {
		met["bun_executable"] = s.bunBin
	}
	if s.nodeBin != "" {
		met["node_executable"] = s.nodeBin
	}
	met["agents_dir"] = filepath.Join(s.prefix, "agents")
	cfg["metabolism"] = met

	srv, _ := cfg["server"].(map[string]any)
	if srv == nil {
		srv = map[string]any{"port": "50051"}
	}
	cfg["server"] = srv
	if p, ok := srv["port"].(string); ok && p != "" {
		s.serverPort = p
	}

	// Embedder is required to boot (dimensions must be explicit, ADR-0021);
	// default to the local bge-large. An existing block is left untouched.
	if _, ok := cfg["embedder"]; !ok {
		cfg["embedder"] = map[string]any{
			"provider":     "ollama",
			"model":        setupEmbedderModel,
			"endpoint":     "http://localhost:11434",
			"dimensions":   1024,
			"timeout_ms":   10000,
			"query_prefix": "Represent this sentence for searching relevant passages: ",
		}
	}

	b, err := json.MarshalIndent(cfg, "", "  ")
	if err != nil {
		return err
	}
	// 0600, not 0644: this file carries the database password in plaintext,
	// and setup's own .env writer already restricts to owner-only for the same
	// reason. (No effect on Windows ACLs; it protects the Unix installs.)
	if err := os.WriteFile(cfgPath, append(b, '\n'), 0o600); err != nil {
		return err
	}

	tuning := filepath.Join(cfgDir, "tuning.json")
	if !fileExists(tuning) {
		tb, err := core.ConfigTemplatesFS.ReadFile("configs/tuning.json")
		if err != nil {
			tb = []byte("{}\n")
		}
		if err := os.WriteFile(tuning, tb, 0o644); err != nil {
			return err
		}
	}
	return os.MkdirAll(filepath.Join(s.prefix, "data"), 0o755)
}

// ---- .env handling (operator credentials, ADR-0047 D13 seeding) --------------------------

// readEnvFile parses KEY=VALUE lines the way the kernel's LoadDotEnv does:
// blank lines and #-comments skipped, value is everything after the first '='
// with surrounding quotes trimmed. A missing file is an empty map, not an error.
func readEnvFile(path string) (map[string]string, error) {
	out := map[string]string{}
	b, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return out, nil
		}
		return nil, err
	}
	for ln := range strings.SplitSeq(string(b), "\n") {
		ln = strings.TrimSpace(ln)
		if ln == "" || strings.HasPrefix(ln, "#") {
			continue
		}
		k, v, ok := strings.Cut(ln, "=")
		if !ok {
			continue
		}
		out[strings.TrimSpace(k)] = strings.Trim(strings.TrimSpace(v), `"'`)
	}
	return out, nil
}

// upsertEnvFile sets keys in a .env file, replacing existing assignments and
// appending missing ones, while preserving every unrelated line and comment.
// The file is created 0600 — it holds credentials.
func upsertEnvFile(path string, kv map[string]string) error {
	var lines []string
	if b, err := os.ReadFile(path); err == nil {
		lines = strings.Split(strings.TrimRight(string(b), "\n"), "\n")
		if len(lines) == 1 && lines[0] == "" {
			lines = nil
		}
	} else if !os.IsNotExist(err) {
		return err
	}
	done := map[string]bool{}
	for i, ln := range lines {
		t := strings.TrimSpace(ln)
		if t == "" || strings.HasPrefix(t, "#") {
			continue
		}
		k, _, ok := strings.Cut(t, "=")
		if !ok {
			continue
		}
		k = strings.TrimSpace(k)
		if _, present := kv[k]; present {
			lines[i] = k + "=" + kv[k]
			done[k] = true
		}
	}
	// Deterministic append order for the remaining keys.
	rest := make([]string, 0, len(kv))
	for k := range kv {
		if !done[k] {
			rest = append(rest, k)
		}
	}
	slices.Sort(rest)
	for _, k := range rest {
		lines = append(lines, k+"="+kv[k])
	}
	return os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o600)
}

// generatePassword returns a ~24-char URL-safe random password (crypto/rand).
// Setup never mints a FIXED default credential (ADR-0047 D13 secure-by-default).
func generatePassword() (string, error) {
	b := make([]byte, 18)
	if _, err := cryptorand.Read(b); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(b), nil
}

