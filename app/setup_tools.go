// ---- process execution & probes ----------------------------------------------------------

// exec runs a command with a timeout and returns trimmed combined output.
func (s *setupState) exec(ctx context.Context, timeout time.Duration, name string, args ...string) (string, bool) {
	cctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	cmd := exec.CommandContext(cctx, name, args...)
	out, err := cmd.CombinedOutput()
	return strings.TrimSpace(string(out)), err == nil
}

// execIn is exec with an explicit working directory (bun install runs in each
// agent package dir, ADR-0125).
func (s *setupState) execIn(ctx context.Context, dir string, timeout time.Duration, name string, args ...string) (string, bool) {
	cctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	cmd := exec.CommandContext(cctx, name, args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	return strings.TrimSpace(string(out)), err == nil
}

// probe checks a tool via `--version` and returns its first output line.
func (s *setupState) probe(ctx context.Context, name string) (string, bool) {
	out, ok := s.exec(ctx, 8*time.Second, name, "--version")
	if !ok {
		return "", false
	}
	return strings.TrimSpace(strings.SplitN(out, "\n", 2)[0]), true
}

func tcpOpen(addr string, timeout time.Duration) bool {
	c, err := net.DialTimeout("tcp", addr, timeout)
	if err != nil {
		return false
	}
	_ = c.Close()
	return true
}

// containsModel reports whether `ollama list` output mentions the model
// (matching the bare name, ignoring any :tag suffix).
func containsModel(list, model string) bool {
	return strings.Contains(list, strings.SplitN(model, ":", 2)[0])
}

// ---- database probes ---------------------------------------------------------------------

func (s *setupState) dbDSN() string {
	u := &url.URL{
		Scheme: "postgres",
		User:   url.UserPassword(s.db.user, s.db.password),
		Host:   net.JoinHostPort(s.db.host, s.db.port),
		Path:   "/" + s.db.dbname,
	}
	return u.String()
}

// dbPing is a real connect+ping (not a TCP probe — Postgres accepts TCP before
// it is ready to authenticate during container start).
func (s *setupState) dbPing(ctx context.Context) error {
	cctx, cancel := context.WithTimeout(ctx, 3*time.Second)
	defer cancel()
	conn, err := pgx.Connect(cctx, s.dbDSN())
	if err != nil {
		return err
	}
	defer conn.Close(cctx)
	return conn.Ping(cctx)
}

func (s *setupState) waitForDB(ctx context.Context, tries int) bool {
	for range tries {
		if s.dbPing(ctx) == nil {
			return true
		}
		select {
		case <-ctx.Done():
			return false
		case <-time.After(time.Second):
		}
	}
	return false
}

// pgvectorAvailable checks the extension is installable — the migrations
// (ADR-0021/0064) hard-require it, so failing early beats a mid-migrate error.
func (s *setupState) pgvectorAvailable(ctx context.Context) (bool, error) {
	cctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	conn, err := pgx.Connect(cctx, s.dbDSN())
	if err != nil {
		return false, err
	}
	defer conn.Close(cctx)
	var n int
	if err := conn.QueryRow(cctx, "SELECT count(*) FROM pg_available_extensions WHERE name = 'vector'").Scan(&n); err != nil {
		return false, err
	}
	return n > 0, nil
}

// ---- readiness poll ----------------------------------------------------------------------

// pollHealth polls the kernel's grpc.health.v1 overall ("") status until
// SERVING or the deadline. The overall status is DB-gated (internal/health),
// so SERVING proves boot + database, not just an open port. Delegates to
// probeHealth (lifecycle.go), which handles both plaintext and SEC-03 TLS
// kernels.
func (s *setupState) pollHealth(ctx context.Context, addr string, wait time.Duration) bool {
	deadline := time.Now().Add(wait)
	for time.Now().Before(deadline) {
		status, err := probeHealth(ctx, addr, 2*time.Second)
		if err == nil && status == healthpb.HealthCheckResponse_SERVING {
			return true
		}
		select {
		case <-ctx.Done():
			return false
		case <-time.After(time.Second):
		}
	}
	return false
}

