// Characterization of the SQL renderings of the access predicate (ADR-0149 P0).
//
// Before ADR-0149 P0 there were three hand-written renderings of domain.TagPredicate
// to SQL: the evidence row (query_plane.go), the TEXT[] item column
// (knowledge_assessment_store.go) and the jsonb metadata.tags column
// (pgvector_adapter.go). These two goldens were generated by THOSE renderers,
// before they were consolidated, and pin what every caller got:
//
//   - testdata/fence_render_sql.golden  — the exact SQL text and bound args, per
//     predicate × renderer (no database);
//   - testdata/fence_render_rows.golden — which rows each rendering admits on a
//     real Postgres, per predicate × renderer, and whether that agrees with the
//     authoritative in-memory form (Check, or CheckRow where the row carries parties).
//
// The consolidation must leave both byte-identical. Regenerate only with
// FENCE_UPDATE=1, and only when a fence change is MEANT to change them.
//
// Deliberate regenerations (each touched only the predicate named):
//   - 2026-11-13, "any-of [a b] [] [sales]": an empty any-of clause now renders
//     FALSE in every shape (owner decision; T-20261113-sql-fence-mirrors-skip-an-
//     empty-any-of-clause). Rows went from "a-sales,deal-sales-a-party [≠ Go]" to
//     none "[= Go]" for all six renderings; the golden has no "≠ Go" line left.
//
// TestPg_FenceDifferential (fence_differential_pg_test.go) is the randomized
// companion: it asserts Go/SQL agreement on generated predicates and rows.

const (
	fenceSQLGolden  = "testdata/fence_render_sql.golden"
	fenceRowsGolden = "testdata/fence_render_rows.golden"
)

type fencePred struct {
	name string
	p    *domain.TagPredicate
}

// fencePredicates is the characterization matrix: bypass, maintenance, owner fence,
// required / forbidden / any-of, parties, own-rows OR, empty — and nil.
func fencePredicates() []fencePred {
	alice := []string{"alice"}
	return []fencePred{
		{"nil", nil},
		{"maintenance", domain.ScopeMaintenance},
		{"bypass (system)", &domain.TagPredicate{Bypass: true}},
		{"bypass, owner alice", &domain.TagPredicate{Bypass: true, Owners: alice}},
		{"empty", &domain.TagPredicate{}},
		{"owner alice", &domain.TagPredicate{Owners: alice}},
		{"owners alice+bob", &domain.TagPredicate{Owners: []string{"alice", "bob"}}},
		{"required sales+eu", &domain.TagPredicate{RequiredTags: []string{"sales", "eu"}}},
		{"forbidden confidential+hr", &domain.TagPredicate{ForbiddenTags: []string{"confidential", "hr"}}},
		{"any-of [a b] [] [sales]", &domain.TagPredicate{AnyOfClauses: [][]string{{"a", "b"}, {}, {"sales"}}}},
		{"party deal:acme, identity customer:acme", &domain.TagPredicate{
			PartyScopedTags: []string{"deal:acme"}, PartyIdentities: []string{"customer:acme"}}},
		{"party deal:acme, no identities", &domain.TagPredicate{PartyScopedTags: []string{"deal:acme"}}},
		{"combined", &domain.TagPredicate{
			Owners: alice, RequiredTags: []string{"sales"}, ForbiddenTags: []string{"confidential"},
			AnyOfClauses:    [][]string{{"a", "b"}},
			PartyScopedTags: []string{"deal:acme"}, PartyIdentities: []string{"customer:acme"}}},
		{"own-rows", &domain.TagPredicate{
			Owners: alice, AnyOfClauses: [][]string{{"sales"}}, ForbiddenTags: []string{"hr"},
			OwnRows: &domain.TagPredicate{Owners: alice, ForbiddenTags: []string{"hr"}}}},
		{"own-rows, required + parties", &domain.TagPredicate{
			Owners: alice, RequiredTags: []string{"t1"}, AnyOfClauses: [][]string{{"a"}, {"sales"}},
			PartyScopedTags: []string{"deal:acme"}, PartyIdentities: []string{"customer:acme"},
			OwnRows: &domain.TagPredicate{Owners: alice, RequiredTags: []string{"t1"},
				PartyScopedTags: []string{"deal:acme"}, PartyIdentities: []string{"customer:acme"}}}},
		{"own-rows malformed (other owner)", &domain.TagPredicate{
			Owners: alice, AnyOfClauses: [][]string{{"sales"}},
			OwnRows: &domain.TagPredicate{Owners: []string{"bob"}}}},
	}
}

// fenceRenderer is one rendering as its callers use it: a " AND …" suffix (or a
// goqu expression list, rendered here with Prepared(true)) plus its args.
type fenceRenderer struct {
	name string
	// rowAware: the rendering reads a parties column, so CheckRow (not Check)
	// is the authoritative form it mirrors.
	rowAware bool
	// render returns the SQL fragment and args for the predicate; startIdx is the
	// number of args the caller already bound.
	render func(p *domain.TagPredicate, startIdx int) (string, []any)
	// rowsSQL wraps a fragment into a query over the characterization temp tables
	// that returns the admitted row ids.
	rowsSQL func(frag string) string
}

// goquFragment renders a goqu expression list as the WHERE body a caller's
// query would carry, prepared ($n placeholders) so the args are pinned too.
func goquFragment(table string, exprs []goqu.Expression) (string, []any) {
	ds := dialect.From(goqu.L(table)).Select(goqu.L("id"))
	for _, e := range exprs {
		ds = ds.Where(e)
	}
	sql, args, err := ds.Prepared(true).ToSQL()
	if err != nil {
		return "ERROR " + err.Error(), nil
	}
	return sql, args
}

func fenceRenderers() []fenceRenderer {
	return []fenceRenderer{
		{
			name: "evidence exists (query plane: observations/events/outbox)", rowAware: true,
			render: func(p *domain.TagPredicate, s int) (string, []any) {
				return sqlfence.EvidenceExists(p, "r.evidence_id", s)
			},
			rowsSQL: func(f string) string { return `SELECT r.id FROM fence_ref r WHERE true` + f },
		},
		{
			name: "evidence row (alias e)", rowAware: true,
			render: func(p *domain.TagPredicate, s int) (string, []any) {
				return sqlfence.Evidence("e").Where(p, s)
			},
			rowsSQL: func(f string) string { return `SELECT e.id FROM evidence e WHERE true` + f },
		},
		{
			name: "item (alias ki, TEXT[] classification)",
			render: func(p *domain.TagPredicate, s int) (string, []any) {
				return sqlfence.TextArray("ki.classification").Where(p, s)
			},
			rowsSQL: func(f string) string { return `SELECT ki.id FROM fence_items ki WHERE true` + f },
		},
		{
			name: "text array (catalog: any TEXT[] column)",
			render: func(p *domain.TagPredicate, s int) (string, []any) {
				return sqlfence.TextArray("x.classification").Where(p, s)
			},
			rowsSQL: func(f string) string { return `SELECT x.id FROM fence_items x WHERE true` + f },
		},
		{
			name: "jsonb metadata (unqualified)",
			render: func(p *domain.TagPredicate, _ int) (string, []any) {
				return goquFragment("fence_docs", jsonbFenceForTest(p, ""))
			},
		},
		{
			name: "jsonb metadata (alias c)",
			render: func(p *domain.TagPredicate, _ int) (string, []any) {
				return goquFragment("fence_docs c", jsonbFenceForTest(p, "c"))
			},
		},
	}
}

// renderSafe renders, recording a panic as an outcome rather than failing: the
// evidence renderings dereference a nil predicate, and that is part of what is pinned.
func renderSafe(r fenceRenderer, p *domain.TagPredicate, startIdx int) (sql string, args []any, panicked bool) {
	defer func() {
		if recover() != nil {
			sql, args, panicked = "", nil, true
		}
	}()
	sql, args = r.render(p, startIdx)
	return sql, args, false
}

func fenceSQLSnapshot() string {
	var b strings.Builder
	for _, fp := range fencePredicates() {
		fmt.Fprintf(&b, "## %s\n", fp.name)
		for _, r := range fenceRenderers() {
			sql, args, panicked := renderSafe(r, fp.p, 2)
			fmt.Fprintf(&b, "- %s\n", r.name)
			if panicked {
				b.WriteString("  PANIC\n")
				continue
			}
			fmt.Fprintf(&b, "  sql:  %q\n", sql)
			fmt.Fprintf(&b, "  args: %#v\n", args)
		}
		b.WriteString("\n")
	}
	// document_list.go binds the bare owner fence over documents.tags.
	held := (&domain.TagPredicate{Owners: []string{"alice"}}).HeldOwnerTags()
	fmt.Fprintf(&b, "## document list owner fence\n  sql:  %q\n  args: %#v\n",
		documentOwnerFenceForTest("d.tags", 3), held)
	return b.String()
}

// documentOwnerFenceForTest is the exact expression document_list.go builds for
// its owner fence, with its placeholder at $n.
func documentOwnerFenceForTest(col string, n int) string {
	return sqlfence.OwnerFence(col, n)
}

func compareGolden(t *testing.T, path, got string) {
	t.Helper()
	path = filepath.FromSlash(path)
	if os.Getenv("FENCE_UPDATE") == "1" {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", path)
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	if strings.ReplaceAll(string(want), "\r\n", "\n") != got {
		t.Fatalf("%s changed:\n%s", path, diffLines(string(want), got))
	}
}

func TestFenceRender_SQLGolden(t *testing.T) {
	t.Parallel()
	compareGolden(t, fenceSQLGolden, fenceSQLSnapshot())
}

