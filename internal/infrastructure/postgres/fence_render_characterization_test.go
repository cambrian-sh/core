// fenceTempTables seeds session-local TEMP tables on one connection. TEMP tables
// are searched before the schema, so `evidence` here is the characterization
// table, not the migrated one — the EXISTS rendering names `evidence` literally.
func fenceTempTables(t *testing.T, ctx context.Context, conn *pgxpool.Conn) {
	t.Helper()
	for _, ddl := range []string{
		`CREATE TEMP TABLE evidence (id text PRIMARY KEY, classification text[] NOT NULL, parties text[] NOT NULL)`,
		`CREATE TEMP TABLE fence_ref (id text PRIMARY KEY, evidence_id text NOT NULL)`,
		`CREATE TEMP TABLE fence_items (id text PRIMARY KEY, classification text[] NOT NULL)`,
		`CREATE TEMP TABLE fence_docs (id text PRIMARY KEY, metadata jsonb NOT NULL)`,
	} {
		if _, err := conn.Exec(ctx, ddl); err != nil {
			t.Fatalf("%s: %v", ddl, err)
		}
	}
	for _, r := range fenceRows() {
		tags := nonNil(r.tags)
		meta := map[string]any{"tags": tags}
		for _, q := range []struct {
			sql  string
			args []any
		}{
			{`INSERT INTO evidence VALUES ($1,$2,$3)`, []any{r.id, tags, nonNil(r.parties)}},
			{`INSERT INTO fence_ref VALUES ($1,$1)`, []any{r.id}},
			{`INSERT INTO fence_items VALUES ($1,$2)`, []any{r.id, tags}},
			{`INSERT INTO fence_docs VALUES ($1,$2)`, []any{r.id, meta}},
		} {
			if _, err := conn.Exec(ctx, q.sql, q.args...); err != nil {
				t.Fatalf("seed %s: %v", r.id, err)
			}
		}
	}
}

func TestPg_FenceRender_RowsGolden(t *testing.T) {
	dsn := os.Getenv("PG_TEST_DSN")
	if dsn == "" {
		t.Skip("PG_TEST_DSN not set; skipping integration test that requires PostgreSQL")
	}
	ctx := context.Background()
	pool, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatalf("pool: %v", err)
	}
	t.Cleanup(pool.Close)
	conn, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatalf("acquire: %v", err)
	}
	defer conn.Release()
	fenceTempTables(t, ctx, conn)
	defer func() {
		_, _ = conn.Exec(ctx, `DROP TABLE IF EXISTS pg_temp.evidence, pg_temp.fence_ref, pg_temp.fence_items, pg_temp.fence_docs`) // best-effort: the session ends with the test anyway
	}()

	var b strings.Builder
	for _, fp := range fencePredicates() {
		fmt.Fprintf(&b, "## %s\n", fp.name)
		for _, r := range fenceRenderers() {
			fmt.Fprintf(&b, "- %s: ", r.name)
			var q string
			var args []any
			if r.rowsSQL == nil { // a goqu rendering: the whole statement is rendered
				var exprs []goqu.Expression
				var panicked bool
				func() {
					defer func() { panicked = recover() != nil }()
					if strings.Contains(r.name, "alias c") {
						exprs = jsonbFenceForTest(fp.p, "c")
						q, args, err = dialect.From(goqu.T("fence_docs").As("c")).Select(goqu.I("c.id")).Where(exprs...).Prepared(true).ToSQL()
					} else {
						exprs = jsonbFenceForTest(fp.p, "")
						q, args, err = dialect.From("fence_docs").Select("id").Where(exprs...).Prepared(true).ToSQL()
					}
				}()
				if panicked {
					b.WriteString("PANIC\n")
					continue
				}
				if err != nil {
					t.Fatalf("ToSQL: %v", err)
				}
			} else {
				frag, fargs, panicked := renderSafe(r, fp.p, 0)
				if panicked {
					b.WriteString("PANIC\n")
					continue
				}
				q, args = r.rowsSQL(frag), fargs
			}
			rows, err := conn.Query(ctx, q, args...)
			if err != nil {
				t.Fatalf("%s / %s: %v\n%s", fp.name, r.name, err, q)
			}
			got := orCollect(t, rows, "")
			fmt.Fprintf(&b, "%s", strings.Join(got, ","))
			// Agreement with the authoritative in-memory form, recorded (not
			// asserted) so a divergence is visible in the golden.
			if fp.p != nil {
				var want []string
				for _, row := range fenceRows() {
					var ok bool
					if r.rowAware {
						_, ok = fp.p.CheckRow(row.tags, row.parties)
					} else {
						_, ok = fp.p.Check(row.tags)
					}
					if ok {
						want = append(want, row.id)
					}
				}
				sort.Strings(want)
				if strings.Join(want, ",") == strings.Join(got, ",") {
					b.WriteString("  [= Go]")
				} else {
					fmt.Fprintf(&b, "  [≠ Go: %s]", strings.Join(want, ","))
				}
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	compareGolden(t, fenceRowsGolden, b.String())
}

// jsonbFenceForTest is the jsonb metadata.tags rendering as chunk reads call it.
func jsonbFenceForTest(p *domain.TagPredicate, alias string) []goqu.Expression {
	return sqlfence.JSONBTags(alias).Goqu(p)
}
