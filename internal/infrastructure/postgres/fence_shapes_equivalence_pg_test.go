// Equivalence of the NON-walk shapes (point, history, as_of, current,
// contradictions, aggregate, events) and of entity's own link reads across the
// filter-before-limit / fence-in-SQL rewrite
// (T-20261112-substrate-query-shapes-apply-limit-before-the,
// T-20261112-query-plane-as-of-applies-sql-limit-before-the,
// T-20261112-traverse-still-reads-events-once-per-frontier).
//
// testdata/shape_equivalence.golden was generated by the PRE-rewrite code
// (SHAPEQ_UPDATE=1) and is the definition of correct for every caller whose
// scope does not hide a row a limit would otherwise have cut: the rewrite may
// only change WHICH rows a narrow caller gets once its page would have been
// short — never what a full-scope caller sees, in what order, or with what
// fields. Do not regenerate it to make a failure pass.
//
// The fixture carries an ADR-0147 retired observation and a retired event, so
// the golden also pins that retired rows stay out of every shape.
//
// The file name sorts before migration_guard_test.go on purpose (that test drops
// and recreates the public schema).

const seGolden = "testdata/shape_equivalence.golden"

const seKind = "shapeq_promise"

type seFixture struct {
	*weFixture
	tracer    *countingTracer
	events    *PgEventStore
	links     *PgLinkStore
	knowledge *PgKnowledgeStore
	reg       *domain.RelationRegistry
	pub, ali  domain.EvidenceID
	sec       domain.EvidenceID
	asOf      time.Time
	narrow    *domain.TagPredicate
}

func newShapeEqFixture(t *testing.T) *seFixture {
	t.Helper()
	dsn := os.Getenv("PG_TEST_DSN")
	if dsn == "" {
		t.Skip("PG_TEST_DSN not set; skipping integration test that requires PostgreSQL")
	}
	ctx := context.Background()
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatalf("dsn: %v", err)
	}
	tracer := &countingTracer{}
	cfg.ConnConfig.Tracer = tracer
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatalf("pool: %v", err)
	}
	t.Cleanup(pool.Close)
	clean := func() {
		bg := context.Background()
		for _, q := range []string{
			`DELETE FROM links WHERE source_ref LIKE 'shapeq-%'`,
			`DELETE FROM event_roles WHERE entity_id LIKE 'shapeq/%'`,
			`DELETE FROM events WHERE source_ref LIKE 'shapeq-%'`,
			`DELETE FROM observations WHERE source_ref LIKE 'shapeq-%'`,
			`DELETE FROM typed_row_retirements WHERE source_ref LIKE 'shapeq-%'`,
			`DELETE FROM resolutions WHERE kind = '` + seKind + `'`,
			`DELETE FROM knowledge_items WHERE kind = '` + seKind + `'`,
			`DELETE FROM entities WHERE id LIKE 'shapeq/%'`,
			`DELETE FROM evidence_outbox WHERE evidence_id IN (SELECT id FROM evidence WHERE source_id = 'shapeq-src')`,
			`DELETE FROM evidence WHERE source_id = 'shapeq-src'`,
		} {
			if _, err := pool.Exec(bg, q); err != nil {
				t.Logf("cleanup %q: %v", q, err)
			}
		}
	}
	clean()
	t.Cleanup(clean)

	reg, err := domain.NewRelationRegistry([]domain.RelationSpec{
		{Name: "shapeq_cites", Family: domain.LinkFamilyLineage},
	})
	if err != nil {
		t.Fatalf("relation registry: %v", err)
	}
	f := &seFixture{
		weFixture: &weFixture{
			pool: pool, ctx: ctx,
			base:  time.Date(2026, 5, 1, 12, 0, 0, 0, time.UTC),
			names: map[string]string{}, ev: map[string]string{},
		},
		tracer:    tracer,
		events:    NewPgEventStore(pool, nil),
		links:     NewPgLinkStore(pool, reg),
		knowledge: NewPgKnowledgeStore(pool, nil),
		reg:       reg,
		narrow:    &domain.TagPredicate{RequiredTags: []string{"mail"}, ForbiddenTags: []string{"k-secret"}},
	}
	f.plane = NewPgQueryPlane(pool, f.events, f.knowledge, NewPgEvidenceStore(pool), f.links, NewPgEntityStore(pool), reg)

	evs := NewPgEvidenceStore(pool)
	evidence := func(name string, tags []string) domain.EvidenceID {
		id, _, err := evs.Insert(ctx, domain.Evidence{
			NamespaceID: "default", SourceID: "shapeq-src", SourceKey: name,
			SourceTime: f.base, IngestedAt: f.base,
			ContentHash: domain.CID("sha256:shapeq-" + name), Classification: tags,
		})
		if err != nil {
			t.Fatalf("evidence %s: %v", name, err)
		}
		f.names[string(id)] = "EV:" + name
		return id
	}
	f.pub = evidence("pub", []string{"mail"})
	f.ali = evidence("alice", []string{"mail", "owner:alice"})
	f.sec = evidence("secret", []string{"mail", "k-secret"})

	// Observations of shapeq/m1 temp, oldest first: the two OLDEST are secret,
	// so a history page cut before the scope is all hidden; the newest is
	// retired (ADR-0147) and must appear nowhere.
	obs := func(name string, ev domain.EvidenceID, hoursAgo int, v float64) {
		if _, err := f.events.RecordObservation(ctx, domain.Observation{
			NamespaceID: "default", EntityID: "shapeq/m1", Predicate: "temp",
			Value:      domain.StatementValue{Type: "number", Number: v},
			OccurredAt: f.base.Add(-time.Duration(hoursAgo) * time.Hour), EvidenceID: ev,
			SourceRef: "shapeq-" + name,
		}); err != nil {
			t.Fatalf("observation %s: %v", name, err)
		}
	}
	obs("o1", f.sec, 6, 1)
	obs("o2", f.sec, 5, 2)
	obs("o3", f.pub, 4, 3)
	obs("o4", f.ali, 3, 4)
	obs("o5", f.pub, 2, 5)
	obs("o6", f.pub, 1, 6)

	// Events of shapeq/c1, same layout: two oldest secret, newest retired.
	event := func(name string, ev domain.EvidenceID, hoursAgo int, roles ...string) {
		e := domain.Event{ID: domain.EventID("shapeq-evt-" + name), NamespaceID: "default",
			Type: "shapeq_" + name, OccurredAt: f.base.Add(-time.Duration(hoursAgo) * time.Hour),
			EvidenceID: ev, SourceRef: "shapeq-" + name}
		for i := 0; i+1 < len(roles); i += 2 {
			e.Roles = append(e.Roles, domain.EventRole{Role: roles[i], EntityID: roles[i+1]})
		}
		id, _, err := f.events.RecordEvent(ctx, e)
		if err != nil {
			t.Fatalf("event %s: %v", name, err)
		}
		f.names[string(id)] = "E:" + name
		f.ev[name] = domain.RefPrefixEvent + string(id)
	}
	event("e1", f.sec, 6, "customer", "shapeq/c1", "order", "shapeq/o1")
	event("e2", f.sec, 5, "customer", "shapeq/c1", "order", "shapeq/o2")
	event("e3", f.pub, 4, "customer", "shapeq/c1", "order", "shapeq/o3", "agent", "shapeq/a1")
	event("e4", f.ali, 3, "customer", "shapeq/c1", "order", "shapeq/o4")
	event("e5", f.pub, 2, "customer", "shapeq/c1", "shipment", "shapeq/s1")
	event("e6", f.pub, 1, "customer", "shapeq/c1", "order", "shapeq/o6")
	event("e7", f.pub, 3, "order", "shapeq/o3", "shipment", "shapeq/s3")
	if _, err := f.events.RetireRows(ctx, "default", []string{"shapeq-o6", "shapeq-e6"},
		domain.RetireSourceDeleted, "shapeq-test"); err != nil {
		t.Fatalf("retire: %v", err)
	}

	for _, id := range []string{"shapeq/c1", "shapeq/o1", "shapeq/o3"} {
		if _, err := NewPgEntityStore(pool).EnsureEntity(ctx, domain.Entity{
			NamespaceID: "default", ID: id, FirstSeenEvidence: f.pub,
		}); err != nil {
			t.Fatalf("entity %s: %v", id, err)
		}
	}

	// Links touching entity:shapeq/c1. The store orders a ref's links newest
	// first, and the two NEWEST of each direction are secret.
	n := 0
	link := func(name, from, to string, ev domain.EvidenceID) {
		n++
		if _, err := f.links.PutLink(ctx, domain.Link{
			ID: "shapeq-" + name, NamespaceID: "default", FromRef: from, ToRef: to,
			Relation: "shapeq_cites", State: domain.LinkStateConfirmed,
			Mechanism: domain.LinkMechanismReference, EvidenceID: ev, AssertedBy: "test",
			Producer: "shapeq@1", Confidence: 1, SourceRef: "shapeq-" + name,
			AssertedAt: f.base.Add(time.Duration(n) * time.Minute),
		}); err != nil {
			t.Fatalf("link %s: %v", name, err)
		}
	}
	c1 := domain.EntityRef("shapeq/c1")
	link("out-pub1", c1, f.ev["e3"], f.pub)
	link("out-pub2", c1, f.ev["e5"], f.pub)
	link("out-sec1", c1, f.ev["e1"], f.sec)
	link("out-sec2", c1, f.ev["e2"], f.sec)
	link("in-pub1", f.ev["e3"], c1, f.pub)
	link("in-ali1", f.ev["e4"], c1, f.ali)
	link("in-sec1", f.ev["e1"], c1, f.sec)
	link("in-sec2", f.ev["e2"], c1, f.sec)

	// Knowledge items. Resolutions order by entity then actor, and k0 — the
	// first entity — is entirely secret, so an as_of page cut before the
	// scope is all hidden.
	item := func(name, entity, actor, status string, tags []string, minutes int) {
		id, _, err := f.knowledge.PutItem(ctx, domain.KnowledgeItem{
			NamespaceID: "default", Kind: seKind, EntityID: entity,
			AssertedBy: actor, AssertedAt: f.base.Add(time.Duration(minutes) * time.Minute),
			SourceRef: "shapeq-" + name, Classification: tags,
			Values: []domain.StatementValue{{Predicate: "status", Type: "text", Text: status}},
		})
		if err != nil {
			t.Fatalf("item %s: %v", name, err)
		}
		f.names[string(id)] = "I:" + name
	}
	mail, secret, alice := []string{"mail"}, []string{"mail", "k-secret"}, []string{"mail", "owner:alice"}
	item("k0a", "shapeq/k0", "a@x", "s0a", secret, 1)
	item("k0b", "shapeq/k0", "b@x", "s0b", secret, 2)
	item("k1a", "shapeq/k1", "a@x", "open", mail, 3)
	item("k1b", "shapeq/k1", "b@x", "closed", mail, 4)
	item("k2a", "shapeq/k2", "a@x", "x", secret, 5)
	item("k2b", "shapeq/k2", "b@x", "y", mail, 6)
	item("k3a", "shapeq/k3", "a@x", "z", alice, 7)
	item("k3b", "shapeq/k3", "b@x", "w", mail, 8)
	f.asOf = time.Now().Add(time.Hour)
	return f
}

// renderRows renders a result like the walk golden, with the DB-clock column
// system_from masked; unordered shapes (contradictions groups through a map)
// are sorted so the golden cannot flap.
func (f *seFixture) renderRows(label string, res domain.QueryResult, err error, sortRows bool) string {
	for _, r := range res.Rows {
		if _, ok := r["system_from"]; ok {
			r["system_from"] = "(set)"
		}
	}
	out := f.render(label, res, err)
	if !sortRows || err != nil {
		return out
	}
	lines := strings.Split(strings.TrimSuffix(out, "\n"), "\n")
	head, body := lines[:2], lines[2:]
	sort.Strings(body)
	return strings.Join(append(head, body...), "\n") + "\n"
}

func (f *seFixture) shapeQueries() []struct {
	label   string
	q       domain.KnowledgeQuery
	unorder bool
} {
	from, to := f.base.Add(-48*time.Hour), f.base.Add(time.Hour)
	return []struct {
		label   string
		q       domain.KnowledgeQuery
		unorder bool
	}{
		{"point m1 temp", domain.KnowledgeQuery{Kind: domain.QueryPoint, EntityID: "shapeq/m1", Predicate: "temp"}, false},
		{"history m1 temp", domain.KnowledgeQuery{Kind: domain.QueryHistory, EntityID: "shapeq/m1", Predicate: "temp", From: from, To: to}, false},
		{"history m1 temp limit=2", domain.KnowledgeQuery{Kind: domain.QueryHistory, EntityID: "shapeq/m1", Predicate: "temp", From: from, To: to, Limit: 2}, false},
		{"aggregate m1 count", domain.KnowledgeQuery{Kind: domain.QueryAggregate, EntityID: "shapeq/m1", Predicate: "temp", Aggregate: "count"}, false},
		{"aggregate m1 avg", domain.KnowledgeQuery{Kind: domain.QueryAggregate, EntityID: "shapeq/m1", Predicate: "temp", Aggregate: "avg"}, false},
		{"events c1", domain.KnowledgeQuery{Kind: domain.QueryEvents, EntityID: "shapeq/c1", From: from, To: to}, false},
		{"events c1 limit=2", domain.KnowledgeQuery{Kind: domain.QueryEvents, EntityID: "shapeq/c1", From: from, To: to, Limit: 2}, false},
		{"traverse c1 hops=3", domain.KnowledgeQuery{Kind: domain.QueryTraverse, EntityID: "shapeq/c1", Hops: 3, From: from, To: to}, false},
		{"as_of kind", domain.KnowledgeQuery{Kind: domain.QueryAsOf, ItemKind: seKind, AsOf: f.asOf}, false},
		{"as_of kind limit=2", domain.KnowledgeQuery{Kind: domain.QueryAsOf, ItemKind: seKind, AsOf: f.asOf, Limit: 2}, false},
		{"as_of kind k1", domain.KnowledgeQuery{Kind: domain.QueryAsOf, ItemKind: seKind, AsOf: f.asOf, EntityID: "shapeq/k1"}, false},
		{"current kind", domain.KnowledgeQuery{Kind: domain.QueryCurrent, ItemKind: seKind}, false},
		{"contradictions kind", domain.KnowledgeQuery{Kind: domain.QueryContradictions, ItemKind: seKind}, true},
		{"entity c1", domain.KnowledgeQuery{Kind: domain.QueryEntity, EntityID: "shapeq/c1"}, false},
		{"entity c1 limit=3", domain.KnowledgeQuery{Kind: domain.QueryEntity, EntityID: "shapeq/c1", Limit: 3}, false},
	}
}

func (f *seFixture) snapshot() string {
	var b strings.Builder
	for _, s := range weScopes() {
		for _, q := range f.shapeQueries() {
			// A small limit under a narrow scope is where the rewrite is MEANT
			// to change the answer (a short page becomes a full one); the
			// narrow-scope tests pin that. Only the unfiltered caller is held
			// to the old answer for them.
			if q.q.Limit > 0 && s.scope != domain.ScopeMaintenance {
				continue
			}
			res, err := f.plane.Query(f.ctx, q.q, s.scope)
			b.WriteString(f.renderRows(s.name+" / "+q.label, res, err, q.unorder))
		}
	}
	return b.String()
}

func TestPg_NonWalkShapes_FullScopeAnswersUnchanged(t *testing.T) {
	f := newShapeEqFixture(t)
	got := f.snapshot()
	path := filepath.FromSlash(seGolden)
	if os.Getenv("SHAPEQ_UPDATE") == "1" {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", path)
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	if string(want) != got {
		t.Fatalf("shape answers changed:\n%s", diffLines(string(want), got))
	}
	if again := f.snapshot(); again != got {
		t.Fatalf("snapshot is not deterministic:\n%s", diffLines(got, again))
	}
}

func (f *seFixture) query(t *testing.T, q domain.KnowledgeQuery, scope *domain.TagPredicate) []domain.QueryRow {
	t.Helper()
	res, err := f.plane.Query(f.ctx, q, scope)
	if err != nil {
		t.Fatalf("%s: %v", q.Kind, err)
	}
	return res.Rows
}
