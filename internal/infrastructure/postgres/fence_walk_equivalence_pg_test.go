// Equivalence of the graph-walk shapes (why, traverse, entity + alias closure)
// across the guard-every-node / filter-before-limit / set-based-per-hop rewrite
// (T-20261112-graph-walks-fence-nodes-by-hand-per-lane-one,
// T-20261112-why-traverse-issue-one-query-per-frontier-node,
// T-20261112-substrate-query-shapes-apply-limit-before-the).
//
// `why` is held separately since ADR-0148 changed its default on purpose
// (fence_why_lineage_golden_pg_test.go holds its stored-lineage answer).
//
// testdata/walk_equivalence.golden was generated by the PRE-rewrite code
// (WALKEQ_UPDATE=1) and is the definition of correct for every caller whose
// scope does not hide a row that a limit would otherwise have cut: the rewrite
// may only change WHICH rows a narrow caller gets once its page would have been
// short, never what a full-scope caller sees, in what order, or with what
// fields. Generated ids are rendered as the fixture's own names so the file is
// stable across runs. Do not regenerate it to make a failure pass.
//
// The file name sorts before migration_guard_test.go on purpose (that test drops
// and recreates the public schema).

const weGolden = "testdata/walk_equivalence.golden"

type weFixture struct {
	pool  *pgxpool.Pool
	plane *PgQueryPlane
	ctx   context.Context
	base  time.Time
	// names maps every generated id (event, evidence) to its fixture name.
	names map[string]string
	ev    map[string]string // fixture event name -> "event:<id>"
}

func newWalkEqFixture(t *testing.T) *weFixture {
	t.Helper()
	dsn := os.Getenv("PG_TEST_DSN")
	if dsn == "" {
		t.Skip("PG_TEST_DSN not set; skipping integration test that requires PostgreSQL")
	}
	ctx := context.Background()
	pool, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatalf("pool: %v", err)
	}
	t.Cleanup(pool.Close)
	clean := func() {
		bg := context.Background()
		for _, q := range []string{
			`DELETE FROM links WHERE source_ref LIKE 'walkeq-%'`,
			`DELETE FROM event_roles WHERE entity_id LIKE 'walkeq/%'`,
			`DELETE FROM events WHERE source_ref LIKE 'walkeq-%'`,
			`DELETE FROM entities WHERE id LIKE 'walkeq/%'`,
			`DELETE FROM evidence_outbox WHERE evidence_id IN (SELECT id FROM evidence WHERE source_id = 'walkeq-src')`,
			`DELETE FROM evidence WHERE source_id = 'walkeq-src'`,
		} {
			if _, err := pool.Exec(bg, q); err != nil {
				t.Logf("cleanup %q: %v", q, err)
			}
		}
	}
	clean()
	t.Cleanup(clean)

	reg, err := domain.NewRelationRegistry([]domain.RelationSpec{
		{Name: "walkeq_caused_by", Family: domain.LinkFamilyLineage},
	})
	if err != nil {
		t.Fatalf("relation registry: %v", err)
	}
	events := NewPgEventStore(pool, nil)
	links := NewPgLinkStore(pool, reg)
	f := &weFixture{
		// The goldens were recorded for the operator plane: candidate links are
		// shown only there (ENG-1536, seesReviewCandidates).
		pool: pool, ctx: domain.WithSurface(ctx, domain.SurfaceRef{Kind: domain.SurfaceOperator, ID: "console"}),
		plane: NewPgQueryPlane(pool, events, NewPgKnowledgeStore(pool, nil), nil, links, NewPgEntityStore(pool, nil), reg),
		// A fixed base: the golden renders times as offsets from it.
		base:  time.Date(2026, 3, 1, 12, 0, 0, 0, time.UTC),
		names: map[string]string{}, ev: map[string]string{},
	}

	evs := NewPgEvidenceStore(pool)
	evidence := func(name string, tags []string) domain.EvidenceID {
		id, _, err := evs.Insert(ctx, domain.Evidence{
			NamespaceID: "default", SourceID: "walkeq-src", SourceKey: name,
			SourceTime: f.base, IngestedAt: f.base,
			ContentHash: domain.CID("sha256:walkeq-" + name), Classification: tags,
		})
		if err != nil {
			t.Fatalf("evidence %s: %v", name, err)
		}
		f.names[string(id)] = "EV:" + name
		return id
	}
	pub := evidence("pub", []string{"mail"})
	ali := evidence("alice", []string{"mail", "owner:alice"})
	sec := evidence("secret", []string{"mail", "k-secret"})

	event := func(name string, ev domain.EvidenceID, typ string, hoursAgo int, roles ...string) {
		// An explicit id: the entity-pair lane orders by event id, and a random
		// one would make the golden flap.
		e := domain.Event{ID: domain.EventID("walkeq-evt-" + name), NamespaceID: "default", Type: typ,
			OccurredAt: f.base.Add(-time.Duration(hoursAgo) * time.Hour), EvidenceID: ev,
			SourceRef: "walkeq-" + name}
		for i := 0; i+1 < len(roles); i += 2 {
			e.Roles = append(e.Roles, domain.EventRole{Role: roles[i], EntityID: roles[i+1]})
		}
		id, _, err := events.RecordEvent(ctx, e)
		if err != nil {
			t.Fatalf("event %s: %v", name, err)
		}
		f.names[string(id)] = "E:" + name
		f.ev[name] = domain.RefPrefixEvent + string(id)
	}
	event("order1", pub, "order_placed", 6, "customer", "walkeq/c1", "order", "walkeq/o1")
	event("ship1", pub, "shipment_dispatched", 5, "order", "walkeq/o1", "shipment", "walkeq/s1")
	event("invoice1", sec, "invoice_issued", 4, "order", "walkeq/o1", "customer", "walkeq/c1")
	event("note1", ali, "alice_note", 3, "customer", "walkeq/c1")
	event("order2", pub, "order_placed", 2, "customer", "walkeq/crm1", "order", "walkeq/o2")
	event("complaint1", pub, "complaint", 1, "customer", "walkeq/c1", "shipment", "walkeq/s1")

	for _, id := range []string{"walkeq/c1", "walkeq/o1", "walkeq/o2", "walkeq/s1", "walkeq/crm1", "walkeq/crm2"} {
		if _, err := NewPgEntityStore(pool, nil).EnsureEntity(ctx, domain.Entity{
			NamespaceID: "default", ID: id, FirstSeenEvidence: pub,
		}); err != nil {
			t.Fatalf("entity %s: %v", id, err)
		}
	}

	n := 0
	link := func(id, from, to, rel, state, mech string, ev domain.EvidenceID) {
		n++
		if _, err := links.PutLink(ctx, domain.Link{
			ID: id, NamespaceID: "default", FromRef: from, ToRef: to, Relation: rel,
			State: state, Mechanism: mech, EvidenceID: ev, AssertedBy: "test",
			Producer: "walkeq@1", Confidence: 1, SourceRef: "walkeq-" + id,
			AssertedAt: f.base.Add(time.Duration(n) * time.Minute),
		}); err != nil {
			t.Fatalf("link %s: %v", id, err)
		}
	}
	conf, cand := domain.LinkStateConfirmed, domain.LinkStateCandidate
	ref := domain.LinkMechanismReference
	link("walkeq-l1", f.ev["complaint1"], f.ev["ship1"], "walkeq_caused_by", conf, ref, pub)
	link("walkeq-l2", f.ev["ship1"], f.ev["order1"], "walkeq_caused_by", conf, ref, pub)
	link("walkeq-l3", f.ev["order2"], f.ev["note1"], "walkeq_caused_by", conf, ref, ali)
	link("walkeq-l4", domain.EntityRef("walkeq/o2"), domain.EntityRef("walkeq/o1"), "walkeq_caused_by", conf, ref, pub)
	link("walkeq-l5", f.ev["complaint1"], f.ev["invoice1"], "walkeq_caused_by", cand, domain.LinkMechanismScored, pub)
	link("walkeq-l6", f.ev["invoice1"], f.ev["order1"], "walkeq_caused_by", conf, ref, sec)
	link("walkeq-a1", domain.EntityRef("walkeq/c1"), domain.EntityRef("walkeq/crm1"), domain.RelationSameAs, conf, domain.LinkMechanismDeclared, pub)
	link("walkeq-a2", domain.EntityRef("walkeq/crm1"), domain.EntityRef("walkeq/crm2"), domain.RelationSameAs, conf, domain.LinkMechanismDeclared, ali)
	link("walkeq-a3", domain.EntityRef("walkeq/c1"), domain.EntityRef("walkeq/cand"), domain.RelationSameAs, cand, domain.LinkMechanismScored, pub)
	return f
}

// renderValue rewrites generated ids to fixture names and times to offsets.
func (f *weFixture) renderValue(v any) string {
	switch x := v.(type) {
	case time.Time:
		return "T" + x.Sub(f.base).String()
	case *time.Time:
		if x == nil {
			return "nil"
		}
		return "T" + x.Sub(f.base).String()
	case string:
		return f.renderString(x)
	case map[string]string:
		keys := make([]string, 0, len(x))
		for k := range x {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var b strings.Builder
		for _, k := range keys {
			fmt.Fprintf(&b, "%s=%s,", k, f.renderString(x[k]))
		}
		return "{" + b.String() + "}"
	default:
		return fmt.Sprintf("%v", v)
	}
}

func (f *weFixture) renderString(s string) string {
	for _, prefix := range []string{domain.RefPrefixEvent, ""} {
		if id, ok := strings.CutPrefix(s, prefix); ok {
			if name, known := f.names[id]; known {
				return prefix + name
			}
		}
	}
	return s
}

func (f *weFixture) render(label string, res domain.QueryResult, err error) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## %s\n", label)
	if err != nil {
		fmt.Fprintf(&b, "error: %v\n", err)
		return b.String()
	}
	fmt.Fprintf(&b, "closure_size=%d guarantee=%q\n", res.ClosureSize, res.Guarantee)
	for _, row := range res.Rows {
		if _, ok := row["created_at"]; ok {
			row["created_at"] = "(set)" // a DB clock, not fixture data
		}
		keys := make([]string, 0, len(row))
		for k := range row {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		parts := make([]string, 0, len(keys))
		for _, k := range keys {
			parts = append(parts, k+"="+f.renderValue(row[k]))
		}
		b.WriteString(strings.Join(parts, " ") + "\n")
	}
	return b.String()
}

// weScopes are the callers the golden covers. At the default limit no lane in
// this fixture fills a page, so for every one of them the pre-rewrite answer is
// already the complete one and must not move.
func weScopes() []struct {
	name  string
	scope *domain.TagPredicate
} {
	return []struct {
		name  string
		scope *domain.TagPredicate
	}{
		{"maintenance", domain.ScopeMaintenance},
		{"system", domain.ScopeSystem},
		{"alice", &domain.TagPredicate{Bypass: true, Owners: []string{"alice"}}},
		{"mail-not-secret", &domain.TagPredicate{RequiredTags: []string{"mail"}, ForbiddenTags: []string{"k-secret"}}},
	}
}

func (f *weFixture) snapshot() string {
	from, to := f.base.Add(-48*time.Hour), f.base.Add(time.Hour)
	queries := []struct {
		label string
		q     domain.KnowledgeQuery
	}{
		{"traverse c1 hops=2", domain.KnowledgeQuery{Kind: domain.QueryTraverse, EntityID: "walkeq/c1", Hops: 2, From: from, To: to}},
		{"traverse c1 hops=3 limit=4", domain.KnowledgeQuery{Kind: domain.QueryTraverse, EntityID: "walkeq/c1", Hops: 3, From: from, To: to, Limit: 4}},
		{"entity c1", domain.KnowledgeQuery{Kind: domain.QueryEntity, EntityID: "walkeq/c1"}},
		{"entity c1 expand", domain.KnowledgeQuery{Kind: domain.QueryEntity, EntityID: "walkeq/c1", ExpandAliases: true, Hops: 3}},
		{"events c1 expand", domain.KnowledgeQuery{Kind: domain.QueryEvents, EntityID: "walkeq/c1", ExpandAliases: true, From: from, To: to}},
	}
	var b strings.Builder
	for _, s := range weScopes() {
		for _, q := range queries {
			// A small limit under a narrow scope is exactly where the rewrite
			// is SUPPOSED to change the answer (a short page becomes a full
			// one); TestPg_WalkShapes_NarrowScopeGetsFullPages pins that. Here
			// only the unfiltered caller is held to the old answer for them.
			if q.q.Limit > 0 && s.scope != domain.ScopeMaintenance {
				continue
			}
			res, err := f.plane.Query(f.ctx, q.q, s.scope)
			b.WriteString(f.render(s.name+" / "+q.label, res, err))
		}
	}
	return b.String()
}

func TestPg_WalkShapes_FullScopeAnswersUnchanged(t *testing.T) {
	f := newWalkEqFixture(t)
	got := f.snapshot()
	path := filepath.FromSlash(weGolden)
	if os.Getenv("WALKEQ_UPDATE") == "1" {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", path)
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	if string(want) != got {
		t.Fatalf("walk answers changed:\n%s", diffLines(string(want), got))
	}
	// The snapshot is deterministic run to run: a golden that could flap would
	// prove nothing either way.
	if again := f.snapshot(); again != got {
		t.Fatalf("snapshot is not deterministic:\n%s", diffLines(got, again))
	}
}
